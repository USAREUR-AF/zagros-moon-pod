    output=$(timeout "$budget" "$CATALOG_HELPER" --profile-dir "$GOAT_PROFILE_DIR" \
        --context "$ACTIVE_GOAT_CONTEXT" \
        --slot "$PARTNER_NAMESPACE" --timeout "$helper_budget" 2>&1)
    status=$?
    if [ "$status" -eq 124 ]; then
        echo "not confirmed: catalog read timed out after ${budget}s"
    else
        printf '%s\n' "$output"
    fi
    return "$status"
}

publish_through_local_router() {
    local local_endpoint temp_profile context profile_toml payload
    local_endpoint=$(sed -n 's/^ZENOH_LOCAL_ENDPOINT=//p' "$REPO_DIR/compose/.env" | head -1)
    [ -n "$local_endpoint" ] || { echo "compose/.env has no ZENOH_LOCAL_ENDPOINT" >&2; return 1; }
    context=$ACTIVE_GOAT_CONTEXT
    [ -f "$GOAT_PROFILE_DIR/contexts/$context/profile.toml" ] \
        || { echo "active profile not found under $GOAT_PROFILE_DIR" >&2; return 1; }
    luks_mounted_probe || { echo "$STATE_DIR is not on the LUKS volume" >&2; return 1; }
    temp_profile=$(mktemp -d -p "$STATE_DIR" .acceptance-profile.XXXXXX) || return 1
    VERIFY_TEMP_PROFILE="$temp_profile"
    chmod 700 "$temp_profile"
    mkdir -p "$temp_profile/contexts/$context"
    if ! cp "$GOAT_PROFILE_DIR/config.toml" "$temp_profile/config.toml" \
        || ! cp "$GOAT_PROFILE_DIR/contexts/$context/profile.toml" \
            "$GOAT_PROFILE_DIR/contexts/$context/mtls.cert.pem" \
            "$GOAT_PROFILE_DIR/contexts/$context/mtls.key.pem" \
            "$GOAT_PROFILE_DIR/contexts/$context/ca-roots.pem" \
            "$temp_profile/contexts/$context/"; then
        verify_temp_cleanup
        return 1
    fi
    profile_toml="$temp_profile/contexts/$context/profile.toml"
    if ! sed "s#^[[:space:]]*router_endpoint[[:space:]]*=.*#router_endpoint = \"${local_endpoint}\"#" \
        "$profile_toml" > "${profile_toml}.new" \
        || ! mv "${profile_toml}.new" "$profile_toml"; then
        verify_temp_cleanup; return 1
    fi
    payload=$(mktemp -p "$temp_profile" .payload.XXXXXX) || { verify_temp_cleanup; return 1; }
    VERIFY_PAYLOAD_FILE="$payload"
    PUBLISH_STARTED_AT=$(date +%s)
    PUBLISH_STARTED_UTC=$(utc_from_epoch "$PUBLISH_STARTED_AT")
    DELIVERY_NONCE=$(printf '%04x%04x' "$RANDOM" "$RANDOM")
    DELIVERY_KEY="${PARTNER_NAMESPACE}/test/ping"
    printf '{"acceptance":"moon-pod","timestamp":%s,"nonce":"%s"}\n' \
        "$PUBLISH_STARTED_AT" "$DELIVERY_NONCE" > "$payload"
    timeout "$ROUND_TRIP_TIMEOUT" env GOAT_PROFILE_DIR="$temp_profile" \
        goat --context "$context" pub "$DELIVERY_KEY" --payload-file "$payload"
    local result=$?
    verify_temp_cleanup
    return "$result"
}

