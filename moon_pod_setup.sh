netbird_up_if_needed() {
    local enrollment_rc key_file_arg=()
    if [ -n "$NETBIRD_SETUP_KEY" ] && [ -n "$NETBIRD_SETUP_KEY_FILE" ]; then
        fail "A typed setup key and NETBIRD_SETUP_KEY_FILE are both set."
        echo "  Unset NETBIRD_SETUP_KEY_FILE, or restart without typing the key."
        echo "  Nothing was spent."
        return 1
    fi
    if mesh_ready_probe; then
        ok "netbird already joined, peers connected"
        return 0
    fi
    if mesh_enrollment_state; then enrollment_rc=0; else enrollment_rc=$?; fi
    if [ "$enrollment_rc" -eq 0 ]; then
        warn "NetBird identity is enrolled, but management or peers are not ready"
        echo "  The setup key is already used; netbird up will not run."
        if [ "$MESH_NOT_READY_REASON" = "no peers are connected" ]; then
            echo "  The goat side owns peer group assignment. Wait for that assignment,"
            echo "  then retry Part 2."
        else
            echo "  $MESH_NOT_READY_REASON."
            echo "  The partner checks this host's network path to the management URL,"
            echo "  then retries Part 2."
        fi
        return 1
    elif [ "$enrollment_rc" -ne 1 ]; then
        fail "could not determine whether this host already has a NetBird identity"
        echo "  Refusing to spend a setup key. Run: sudo netbird status --json"
        return 1
    fi
    if [ -z "$NETBIRD_SETUP_KEY" ] && [ -n "$NETBIRD_SETUP_KEY_FILE" ] && ! setup_key_file_secure; then
        fail "NETBIRD_SETUP_KEY_FILE must be a readable regular file with mode 0400 or 0600"
        return 1
    fi
    if [ -z "$NETBIRD_SETUP_KEY" ] && [ -z "$NETBIRD_SETUP_KEY_FILE" ]; then
        warn "netbird is not enrolled and no setup key was supplied"
        return 1
    fi
    if [ -z "$NETBIRD_MANAGEMENT_URL" ]; then
        warn "mesh management URL is missing - take it from the onboarding package"
        return 1
    fi
    if ! valid_label "$POD_ID"; then
        fail "POD_ID '$POD_ID' is not valid."
        show_pod_id_rule
        echo "  The setup key was not read or spent."
        return 1
    fi
    if [ -n "$NETBIRD_SETUP_KEY_FILE" ]; then
        key_file_arg=(--setup-key-file "$NETBIRD_SETUP_KEY_FILE")
    else
        luks_mounted_probe \
            || { fail "$STATE_DIR is not confirmed on the encrypted state volume; setup key was not written or spent"; return 1; }
        NETBIRD_KEY_FILE=$(mktemp -p "$STATE_DIR" .netbird-setup-key.XXXXXX) \
            || { fail "could not create setup-key file on the encrypted state volume"; return 1; }
        chmod 600 "$NETBIRD_KEY_FILE"
        printf '%s' "$NETBIRD_SETUP_KEY" > "$NETBIRD_KEY_FILE" \
            || { fail "could not write protected setup-key file"; return 1; }
        key_file_arg=(--setup-key-file "$NETBIRD_KEY_FILE")
    fi
    warn "netbird is not enrolled - running 'netbird up' now (key will be spent)"
    # Every NetBird with --setup-key-file also supports --hostname.
    if netbird up --management-url "$NETBIRD_MANAGEMENT_URL" "${key_file_arg[@]}" \
        --hostname "$POD_ID" \
        --enable-rosenpass=false --rosenpass-permissive=false; then
        [ -z "$NETBIRD_KEY_FILE" ] || { : > "$NETBIRD_KEY_FILE"; unlink "$NETBIRD_KEY_FILE"; NETBIRD_KEY_FILE=""; }
        ok "netbird up succeeded (management: $NETBIRD_MANAGEMENT_URL)"
        NETBIRD_KEY_SPENT_THIS_RUN=1
        NETBIRD_SETUP_KEY=""
    else
        [ -z "$NETBIRD_KEY_FILE" ] || { : > "$NETBIRD_KEY_FILE"; unlink "$NETBIRD_KEY_FILE"; NETBIRD_KEY_FILE=""; }
        fail "netbird up failed"
        return 1
    fi
    if ! wait_for "netbird mesh connection" "$MESH_WAIT_INTERVAL" "$MESH_WAIT_TRIES" mesh_ready_probe; then
        mesh_ready_probe >/dev/null 2>&1 || true
        fail "netbird up succeeded, but the mesh is not ready: ${MESH_NOT_READY_REASON:-status is unavailable}"
        echo "  The setup key is already used. The goat side owns peer group assignment."
        return 1
    fi
}

# Remove a temporary directory this script created, including read-only files.
remove_temp_dir() {
    [ -n "$1" ] && [ -d "$1" ] || return 0
    find "$1" -type f -exec chmod u+w {} + 2>/dev/null || true
    find "$1" \( -type f -o -type l \) -delete
    find "$1" -depth -type d -empty -delete
}

verify_temp_cleanup() {
    if [ -n "${VERIFY_PAYLOAD_FILE:-}" ] && [ -f "$VERIFY_PAYLOAD_FILE" ]; then
        : > "$VERIFY_PAYLOAD_FILE"; unlink "$VERIFY_PAYLOAD_FILE"
    fi
    VERIFY_PAYLOAD_FILE=""
    remove_temp_dir "${VERIFY_TEMP_PROFILE:-}"
    VERIFY_TEMP_PROFILE=""
}

goat_install_temp_cleanup() {
    remove_temp_dir "${GOAT_INSTALL_TEMP_DIR:-}"
    GOAT_INSTALL_TEMP_DIR=""
}

goat_checksum_matches() {
    local binary="$1" checksum_file="$2" line expected actual name
    local -a lines
    [ -f "$binary" ] && [ -f "$checksum_file" ] || return 1
    mapfile -t lines < "$checksum_file" || return 1
    [ "${#lines[@]}" -eq 1 ] || return 1
    line=${lines[0]}
    [ -n "$line" ] || return 1
    [[ "$line" =~ ^([0-9A-Fa-f]{64})\ [\ *](.+)$ ]] || return 1
    expected=${BASH_REMATCH[1],,}
    name=${BASH_REMATCH[2]}
    [ "$name" = "$(basename "$binary")" ] || return 1
    actual=$(sha256sum "$binary" 2>/dev/null | awk '{print tolower($1)}') \
        || return 1
    [ "$actual" = "$expected" ]
}

install_goat_binary() {
    local source_binary="$1" source_checksum copy_binary copy_checksum new_sha
    source_checksum="${source_binary}.sha256"
    GOAT_INSTALL_TEMP_DIR=$(mktemp -d) || {
        fail "could not create a temporary directory for the goat binary"
        return 1
    }
    chmod 700 "$GOAT_INSTALL_TEMP_DIR"
    copy_binary="$GOAT_INSTALL_TEMP_DIR/$(basename "$source_binary")"
    copy_checksum="$GOAT_INSTALL_TEMP_DIR/$(basename "$source_checksum")"
    if ! cp "$source_binary" "$copy_binary" 2>/dev/null \
            || ! cp "$source_checksum" "$copy_checksum" 2>/dev/null \
            || ! goat_checksum_matches "$copy_binary" "$copy_checksum"; then
        fail "refusing an unverified goat binary: its checksum file is missing,"
        echo "  malformed, names another file, or does not match."
        goat_install_temp_cleanup
        return 1
    fi
    new_sha=$(sha256sum "$copy_binary" | awk '{print $1}')
    if [ -n "$CURRENT_SHA" ] && [ "$new_sha" = "$CURRENT_SHA" ]; then
        ok "goat already up to date"
    elif install -m 755 "$copy_binary" /usr/local/bin/goat; then
        [ -n "$CURRENT_SHA" ] \
            && ok "updated goat from $source_binary" \
            || ok "installed goat from $source_binary"
    else
        fail "could not install the verified goat binary"
        goat_install_temp_cleanup
        return 1
    fi
    goat_install_temp_cleanup
}

download_goat_binary() {
    local base="$1" arch="$2" destination="$3"
    if curl -fsSL --connect-timeout 10 --max-time 300 \
        -o "$destination/goat-linux-${arch}" "$base/goat-linux-${arch}" \
        && curl -fsSL --connect-timeout 10 --max-time 30 \
            -o "$destination/goat-linux-${arch}.sha256" \
            "$base/goat-linux-${arch}.sha256"; then
        SOURCE_BIN="$destination/goat-linux-${arch}"
        ok "downloaded goat through the already-ready mesh"
    elif [ -n "$CURRENT_SHA" ]; then
        warn "could not reach the download service; keeping the installed goat"
    else
        fail "could not download goat from the mesh-only download service"
        echo "  Copy goat-linux-${arch} and its .sha256 beside this script, then re-run Part 1."
    fi
}

cleanup() {
    [ "${CLEANUP_DONE:-0}" = "0" ] || return 0
    CLEANUP_DONE=1
    verify_temp_cleanup
    goat_install_temp_cleanup
    if [ -n "${NETBIRD_KEY_FILE:-}" ] && [ -f "$NETBIRD_KEY_FILE" ]; then
        : > "$NETBIRD_KEY_FILE"
        unlink "$NETBIRD_KEY_FILE"
    fi
}
