audit_samples_total() {
    local budget="${1:-$AUDIT_METRICS_TIMEOUT}" metrics total
    [ "$budget" -gt "$AUDIT_METRICS_TIMEOUT" ] && budget=$AUDIT_METRICS_TIMEOUT
    [ "$budget" -lt 1 ] && budget=1
    metrics=$(curl -fsS --connect-timeout "$budget" --max-time "$budget" \
        "$AUDIT_METRICS_URL" 2>/dev/null) || return 1
    total=$(printf '%s\n' "$metrics" \
        | awk '$1 ~ /^goat_audit_samples_total({|$)/ { found=1; total += $2 }
               $1 ~ /^goat_audit_subscriber_session_state({|$)/ { audit_sink=1 }
               END { if (found) print total; else if (audit_sink) print 0; else exit 1 }') \
        || return 1
    [[ "$total" =~ ^[0-9]+([.][0-9]+)?$ ]] || return 1
    printf '%s\n' "$total"
}

