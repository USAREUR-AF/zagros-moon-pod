}

POD_ID_RULE="1-59 lowercase letters, digits, or hyphens, starting and ending with a letter or digit"
show_pod_id_rule() { printf 'Required form: %s.\n' "$POD_ID_RULE" | fold -s -w 74 | sed 's/^/  /'; }
valid_slot() { [[ "$1" =~ ^[A-Za-z0-9/_-]+$ ]] && [[ "$1" != CHANGE-ME* ]]; }
valid_label() { [[ "$1" =~ ^[a-z0-9]([a-z0-9-]{0,57}[a-z0-9])?$ ]]; }
valid_goatnet() {
    [ "$1" = "your.goatnet.domain" ] \
        || [[ "$1" =~ ^[A-Za-z0-9]([A-Za-z0-9.-]*[A-Za-z0-9])?$ ]]
}
valid_management_url() { [ -z "$1" ] || [[ "$1" =~ ^https://[A-Za-z0-9]([A-Za-z0-9.-]*[A-Za-z0-9])?(:[0-9]+)?/?$ ]]; }
valid_absolute_path() { [ -z "$1" ] || [[ "$1" = /* ]] && [[ "$1" != *$'\n'* ]]; }
valid_fingerprint() { [ -z "$1" ] || [[ "$1" =~ ^(SHA256:)?[0-9A-Fa-f]{64}$ ]]; }

saved_assignment() {
    local file="$1" key="$2" validator="$3" lines count value
    [ -f "$file" ] || return 1
    lines="$(grep -E "^${key}=" "$file" 2>/dev/null || true)"
    count="$(printf '%s\n' "$lines" | grep -c . || true)"
    [ "$count" -eq 1 ] || {
        [ "$count" -gt 1 ] && echo "Ignoring duplicate $key entries in $file" >&2
        return 1
    }
    value="${lines#*=}"
    "$validator" "$value" || { echo "Ignoring invalid saved $key in $file" >&2; return 1; }
    printf '%s\n' "$value"
}

first_saved_assignment() {
    local key="$1" validator="$2" file value; shift 2
    for file in "$@"; do
        if value="$(saved_assignment "$file" "$key" "$validator")"; then
            printf '%s\n' "$value"
            return 0
        fi
    done
    return 1
}

load_saved_inputs() {
    local profile="$REPO_DIR/profiles/$PROFILE_NAME/profile.env"
    local compose="$REPO_DIR/compose/.env" value spec key validator from_env
    if [ "$ENV_PARTNER_NAMESPACE_SET" -ne 1 ]; then
        value="$(first_saved_assignment PARTNER_NAMESPACE valid_slot "$INPUT_STATE_FILE" "$profile" "$compose" 2>/dev/null)" \
            || value=""
        [ -n "$value" ] && PARTNER_NAMESPACE="$value"
    fi
    if [ "$ENV_POD_ID_SET" -ne 1 ]; then
        SAVED_POD_ID_REJECTED=""
        if value="$(first_saved_assignment POD_ID valid_label \
                "$INPUT_STATE_FILE" "$profile" "$compose" 2>/dev/null)"; then
            POD_ID="$value"
            POD_ID_EXPLICIT=1
        elif value="$(first_saved_assignment POD_ID true \
                "$INPUT_STATE_FILE" "$profile" "$compose" 2>/dev/null)" \
                && ! valid_label "$value"; then
            SAVED_POD_ID_REJECTED="$value"
        fi
    fi
    for spec in "GOATNET:valid_goatnet:$ENV_GOATNET_SET" \
            "NETBIRD_MANAGEMENT_URL:valid_management_url:$ENV_MANAGEMENT_SET" \
            "BUNDLE_TARBALL:valid_absolute_path:$ENV_BUNDLE_TARBALL_SET" \
            "BUNDLE_PATH:valid_absolute_path:$ENV_BUNDLE_PATH_SET" \
            "CA_ROOT_PEM:valid_absolute_path:$ENV_CA_ROOT_SET" \
            "EXPECTED_CA_FINGERPRINT:valid_fingerprint:$ENV_CA_FP_SET"; do
        IFS=: read -r key validator from_env <<< "$spec"
        [ "$from_env" -ne 1 ] || continue
        value="$(first_saved_assignment "$key" "$validator" "$INPUT_STATE_FILE" 2>/dev/null)" \
            && [ -n "$value" ] && printf -v "$key" '%s' "$value"
    done
    PARTNER_NAMESPACE="${PARTNER_NAMESPACE:-CHANGE-ME-zagros-uuid-slot}"
    POD_ID="${POD_ID:-moon-pod}"
    GOATNET="${GOATNET:-your.goatnet.domain}"
    [ -n "$BUNDLE_TARBALL" ] || BUNDLE_TARBALL="$REAL_HOME/${POD_ID}-bundle.tar.gz"
    [ -n "$BUNDLE_PATH" ] || BUNDLE_PATH="$REAL_HOME/goat-bundle/${PARTNER_NAMESPACE}-goat-cli.cbor"
}

persist_inputs() {
    local dir tmp saved_tarball="$BUNDLE_TARBALL" saved_bundle="$BUNDLE_PATH"
    [ "$BUNDLE_TARBALL" != "$REAL_HOME/${POD_ID}-bundle.tar.gz" ] \
        || saved_tarball=""
    [ "$BUNDLE_PATH" != "$REAL_HOME/goat-bundle/${PARTNER_NAMESPACE}-goat-cli.cbor" ] \
        || saved_bundle=""
    dir="$(dirname "$INPUT_STATE_FILE")"
    if [ ! -d "$dir" ]; then
        cp -r "$REPO_DIR/profiles/$SOURCE_PROFILE" "$dir" || return 1
    fi
    if command -v git >/dev/null 2>&1 \
        && git -C "$REPO_DIR" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
        git -C "$REPO_DIR" check-ignore -q "profiles/$PROFILE_NAME/setup-inputs.env" \
            || { fail "$INPUT_STATE_FILE is not git-ignored; refusing to save inputs"; return 1; }
    else
        warn "not a git checkout - saving inputs without a git-ignore check"
    fi
    tmp="$(mktemp -p "$dir" .setup-inputs.XXXXXX)" || return 1
    chmod 600 "$tmp"
    {
        printf 'PARTNER_NAMESPACE=%s\n' "$PARTNER_NAMESPACE"
        printf 'POD_ID=%s\n' "$POD_ID"
        printf 'GOATNET=%s\n' "$GOATNET"
        printf 'NETBIRD_MANAGEMENT_URL=%s\n' "$NETBIRD_MANAGEMENT_URL"
        printf 'BUNDLE_TARBALL=%s\n' "$saved_tarball"
        printf 'BUNDLE_PATH=%s\n' "$saved_bundle"
        printf 'CA_ROOT_PEM=%s\n' "$CA_ROOT_PEM"
        printf 'EXPECTED_CA_FINGERPRINT=%s\n' "$EXPECTED_CA_FINGERPRINT"
    } > "$tmp" || { unlink "$tmp"; return 1; }
    mv "$tmp" "$INPUT_STATE_FILE"
}

# Generic poll: wait_for "description" interval tries probe_fn [args...]
# (only used WITHIN a running part, for things the part itself just kicked off -
#  not for anything the user has to go fetch, that's what the menu gate is for)
wait_for() {
    local desc="$1" interval="$2" tries="$3"; shift 3
    local i=1
    while [ "$i" -le "$tries" ]; do
        if "$@" >/dev/null 2>&1; then
            echo; ok "$desc (ready after ~$(( (i - 1) * interval ))s)"; return 0
        fi
        if [ -t 1 ]; then
            printf "${CYAN}${BOLD}[WAIT]${RESET} %-55s try %d/%d (checking every %ss)\r" \
                "$desc" "$i" "$tries" "$interval"
        else
            printf "[WAIT] %s (try %d/%d, every %ss)\n" "$desc" "$i" "$tries" "$interval"
        fi
        sleep "$interval"; i=$((i + 1))
    done
    echo; warn "$desc - still not ready after $((tries * interval))s"; return 1
}

