        fail "The saved POD_ID '$SAVED_POD_ID_REJECTED' is not in the required form."
        show_pod_id_rule
        echo "  Choose Configure inputs and type a POD_ID in that form."
        echo "  If it came from the goat side, ask them to confirm the corrected value."
        return 1
    elif [ "$POD_ID_EXPLICIT" -ne 1 ]; then
        fail "POD_ID is missing or invalid; get it from the goat-side welcome package"
        show_pod_id_rule
        return 1
    fi
    if ! valid_absolute_path "$BUNDLE_TARBALL" || ! valid_absolute_path "$BUNDLE_PATH"; then
        fail "the signed join bundle paths are invalid; choose Configure inputs"; return 1
    fi
    bundle_present_probe \
        || { fail "the signed join bundle is missing; get the tarball or .cbor from the goat side"; return 1; }
    valid_absolute_path "$CA_ROOT_PEM" \
        || { fail "CA_ROOT_PEM is invalid; get the CA root from the goat side"; return 1; }
