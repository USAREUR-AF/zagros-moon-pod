    if ! valid_label "$POD_ID"; then
        fail "POD_ID '$POD_ID' is not valid."
        show_pod_id_rule
        press_enter; return 1
    fi
    SAVED_POD_ID_REJECTED=""
    if ! valid_slot "$PARTNER_NAMESPACE"; then fail "invalid or placeholder PARTNER_NAMESPACE '$PARTNER_NAMESPACE'"; press_enter; return 1; fi
    if [ "$GOATNET" = "your.goatnet.domain" ] || ! valid_goatnet "$GOATNET"; then
        fail "invalid GOATNET '$GOATNET'"; press_enter; return 1
    fi
    if [ -z "$NETBIRD_MANAGEMENT_URL" ] || ! valid_management_url "$NETBIRD_MANAGEMENT_URL"; then
        fail "NETBIRD_MANAGEMENT_URL must be an https:// URL"; press_enter; return 1
    fi
    if ! valid_absolute_path "$BUNDLE_TARBALL" || ! valid_absolute_path "$BUNDLE_PATH" \
        || ! valid_absolute_path "$CA_ROOT_PEM"; then
        fail "bundle and public-key paths must be absolute"; press_enter; return 1
    fi
    if ! valid_fingerprint "$EXPECTED_CA_FINGERPRINT"; then
        fail "CA root fingerprint must be SHA256: followed by 64 hex digits"; press_enter; return 1
    fi
    local enrollment_rc
    if command -v netbird >/dev/null 2>&1; then
        if mesh_enrollment_state; then enrollment_rc=0; else enrollment_rc=$?; fi
    else
        # Configure-before-Part-1 is the documented bare-host path. NetBird cannot
        # have an identity before it is installed, so collect the in-memory key now.
        enrollment_rc=1
    fi
    if [ "$enrollment_rc" -eq 1 ]; then
        read -r -s -p "  NETBIRD_SETUP_KEY (hidden; Enter keeps current value): " value; echo
        [ -n "$value" ] && NETBIRD_SETUP_KEY="$value"
    elif [ "$enrollment_rc" -eq 0 ]; then
        info "NetBird is already enrolled; no setup key was requested"
    else
        warn "NetBird enrollment state is unknown; no setup key was requested"
    fi
    if ! persist_inputs; then fail "could not save inputs in the git-ignored local profile"; press_enter; return 1; fi
    ok "non-secret inputs saved in the git-ignored local profile for the next run"
    info "the setup key was kept only in memory and was not printed or saved"
    press_enter
}

