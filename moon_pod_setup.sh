classify_delivery_outcome() {
    local publish_ok="$1" audit_readable="$2" local_observed="$3"
    local catalog_readable="$4" fabric_observed="$5"
    if [ "$publish_ok" -ne 1 ]; then echo "Publish failed"
    elif [ "$audit_readable" -ne 1 ]; then echo "Not verified"
    elif [ "$local_observed" -ne 1 ]; then echo "Not delivered"
    elif [ "$catalog_readable" -ne 1 ]; then echo "Not verified"
    elif [ "$fabric_observed" -ne 1 ]; then echo "Local only"
    else echo "Delivered"
    fi
}

run_delivery_check() {
    local started now remaining attempt=0 output status count published retry sleep_for
    local after_local catalog_stop=0 published_display
    DELIVERY_KEY=""; DELIVERY_NONCE=""
    PUBLISH_STARTED_AT=""; PUBLISH_STARTED_UTC=""
    DELIVERY_DETAIL=""; LAST_CATALOG_ERROR=""
    PUBLISH_OK=0; AUDIT_READABLE=0; AUDIT_POLL_READABLE=0; LOCAL_OBSERVED=0
    CATALOG_BASELINE_READABLE=0; CATALOG_POLL_READABLE=0; FABRIC_OBSERVED=0
    BEFORE_LOCAL=$(audit_samples_total); BEFORE_LOCAL_STATUS=$?
    [ "$BEFORE_LOCAL_STATUS" -eq 0 ] && AUDIT_READABLE=1
    if [ "$AUDIT_READABLE" -ne 1 ]; then
        DELIVERY_DETAIL="the local audit metric could not be read; start or repair goat-moon-audit-sink, then retry Part 3"
        DELIVERY_OUTCOME="Not verified"
        return 0
    fi

    CATALOG_HELPER="$REPO_DIR/host/catalog-publish-count.py"
    BASELINE_OUT=$(catalog_count_read); BASELINE_STATUS=$?
    if [ "$BASELINE_STATUS" -eq 0 ] \
        && [[ "$BASELINE_OUT" =~ ^([0-9]+)$'\t'([0-9]+)$ ]]; then
        BASELINE_COUNT=${BASH_REMATCH[1]}
        BASELINE_PUBLISHED=${BASH_REMATCH[2]}
        CATALOG_BASELINE_READABLE=1
        published_display=$(catalog_time_display "$BASELINE_PUBLISHED")
        echo "  baseline: publish_count=$BASELINE_COUNT last_publish_at=$published_display"
    else
        LAST_CATALOG_ERROR=${BASELINE_OUT:-"not confirmed: catalog baseline was unreadable"}
        warn "$LAST_CATALOG_ERROR"
    fi

    if publish_through_local_router; then
        PUBLISH_OK=1
        ok "publish accepted by the running local router"
        echo "  key=$DELIVERY_KEY"
        echo "  nonce=$DELIVERY_NONCE"
        echo "  started=$PUBLISH_STARTED_UTC"
    else
        DELIVERY_DETAIL="the local publish returned an error; check the router logs and retry Part 3"
        DELIVERY_OUTCOME=$(classify_delivery_outcome 0 "$AUDIT_READABLE" 0 0 0)
        return 0
    fi

    started=$(date +%s)
    while :; do
        output=""; status=0
        now=$(date +%s); remaining=$((FABRIC_CONFIRM_TIMEOUT - (now - started)))
        [ "$remaining" -ge 2 ] || break
        attempt=$((attempt + 1))
        info "delivery poll $attempt (elapsed $((now - started))s, ${remaining}s remaining)"

        if [ "$LOCAL_OBSERVED" -eq 0 ] \
                && after_local=$(audit_samples_total "$remaining"); then
            AUDIT_POLL_READABLE=1
            awk -v before="$BEFORE_LOCAL" -v after="$after_local" \
                'BEGIN { exit !(after > before) }' && LOCAL_OBSERVED=1
        fi

        if [ "$CATALOG_BASELINE_READABLE" -eq 1 ] \
                && [ "$catalog_stop" -eq 0 ] && [ "$FABRIC_OBSERVED" -eq 0 ]; then
            output=$(catalog_count_read "$remaining"); status=$?
            if [ "$status" -eq 0 ] \
                && [[ "$output" =~ ^([0-9]+)$'\t'([0-9]+)$ ]]; then
                CATALOG_POLL_READABLE=1
                count=${BASH_REMATCH[1]}; published=${BASH_REMATCH[2]}
                published_display=$(catalog_time_display "$published")
                echo "  publish_count=$count last_publish_at=$published_display"
                if fabric_evidence_is_current "$BASELINE_COUNT" "$count" "$published" "$PUBLISH_STARTED_AT"; then
                    FABRIC_OBSERVED=1
                fi
            else
                CATALOG_POLL_READABLE=0
                LAST_CATALOG_ERROR=${output:-"not confirmed: catalog response was unreadable"}
                echo "  $LAST_CATALOG_ERROR"
                [ "$status" -eq 2 ] && catalog_stop=1
            fi
        fi

        [ "$LOCAL_OBSERVED" -eq 1 ] && [ "$FABRIC_OBSERVED" -eq 1 ] && break
        [ "$LOCAL_OBSERVED" -eq 1 ] && [ "$CATALOG_BASELINE_READABLE" -ne 1 ] && break
        [ "$LOCAL_OBSERVED" -eq 1 ] && [ "$catalog_stop" -eq 1 ] && break
        now=$(date +%s); remaining=$((FABRIC_CONFIRM_TIMEOUT - (now - started)))
        [ "$remaining" -gt 0 ] || break
        sleep_for=$FABRIC_COUNT_RETRY_DELAY
        if [ "${status:-0}" -eq 3 ] && [[ "${output:-}" =~ retry-after-seconds=([0-9]+) ]]; then
            retry=${BASH_REMATCH[1]}; [ "$retry" -gt "$sleep_for" ] && sleep_for=$retry
        fi
        [ "$sleep_for" -gt "$remaining" ] && sleep_for=$remaining
        sleep "$sleep_for"
    done

    DELIVERY_OUTCOME=$(classify_delivery_outcome "$PUBLISH_OK" \
        "$(( AUDIT_READABLE && AUDIT_POLL_READABLE ))" \
        "$LOCAL_OBSERVED" "$(( CATALOG_BASELINE_READABLE && CATALOG_POLL_READABLE ))" \
        "$FABRIC_OBSERVED")
    case "$DELIVERY_OUTCOME" in
        "Not delivered")
            DELIVERY_DETAIL="the local audit counter did not rise; inspect goat-moon-audit-sink and the router, then retry Part 3" ;;
        "Not verified")
            if [ "$AUDIT_POLL_READABLE" -ne 1 ]; then
                DELIVERY_DETAIL="the local audit count could not be read after publishing; repair goat-moon-audit-sink, then retry Part 3"
            else
                DELIVERY_DETAIL="${LAST_CATALOG_ERROR:-the catalog count could not be read}; retry Part 3, then share this cause with the goat side if it persists"
            fi ;;
        "Local only")
            DELIVERY_DETAIL="local delivery passed, but the slot catalog count did not rise; send the key, nonce, and UTC time above to the goat-side operator" ;;
        "Delivered")
            DELIVERY_DETAIL="the local audit count and the slot-wide catalog count both rose; the catalog cannot identify which message caused its rise" ;;
    esac
}

finish_part3() {
    local i return_status
    case "$PART3_RESULT" in
        verified) banner "VERIFIED" "$GREEN"; return_status=0 ;;
        not-verified) banner "NOT VERIFIED" "$YELLOW"; return_status=2 ;;
        *) banner "FAILED" "$RED"; return_status=1 ;;
    esac
    for i in "${!SUMMARY_LABELS[@]}"; do
        printf "  %-18s %s\n" "${SUMMARY_LABELS[$i]}:" "${SUMMARY_STATUS[$i]}"
    done
    echo
    case "$PART3_RESULT" in
        verified)
            echo "  Proven: local checks passed, and both local and slot-wide counts rose."
            echo "  Not proven: that this exact message caused the catalog rise, bilateral inbound"
            echo "  delivery, topic declaration, restart recovery, or durable audit retention." ;;
        not-verified)
            echo "  No check failed, but delivery could not be verified."
            printf '%s\n' "$DELIVERY_DETAIL" | fold -s -w 74 | sed 's/^/  /' ;;
        *)
            echo "  Fix each failed check or delivery condition above, then re-run Part 3." ;;
    esac
    return "$return_status"
}

run_part3() {
    banner "PART 3 / 3  --  VERIFY" "$BLUE"
    PART3_RESULT="failed"
    SUMMARY_LABELS=(); SUMMARY_STATUS=()
    LOCAL_CHECKS_FAILED=0
    info "Slot ID = $PARTNER_NAMESPACE"
    echo "  Root-owned profile:"
    printf '%s\n' "$GOAT_PROFILE_DIR" | fold -w 74 | sed 's/^/    /'

    if ! cleanup_stale_acceptance_profiles; then
        note_fail "3.0 (Storage)" "$STATE_DIR is not confirmed on the LUKS volume; nothing was published."
        record "Local checks" "FAIL"; record "Delivery" "Not run"
        DELIVERY_DETAIL="the protected acceptance profile could not be created"
        finish_part3; return $?
    fi
    if ! valid_slot "$PARTNER_NAMESPACE"; then
        note_fail "3.0 (Inputs)" "Slot ID is missing or still a placeholder. Choose Configure inputs; nothing was published."
        record "Local checks" "FAIL"; record "Delivery" "Not run"
        DELIVERY_DETAIL="the slot ID is invalid; nothing was published"
        finish_part3; return $?
    fi
    if ! valid_label "$POD_ID"; then
        note_fail "3.0 (Inputs)" "POD_ID is invalid. Required form:
$(printf '%s.' "$POD_ID_RULE" | fold -s -w 76)
Choose Configure inputs; nothing was published."
        record "Local checks" "FAIL"; record "Delivery" "Not run"
        DELIVERY_DETAIL="the POD ID is invalid; nothing was published"
        finish_part3; return $?
    fi
    ROUTER_NAMESPACE=$(sed -n 's/^PARTNER_NAMESPACE=//p' \
        "$REPO_DIR/compose/.env" 2>/dev/null | head -1)
    if [ -z "$ROUTER_NAMESPACE" ]; then
        note_fail "3.0 (Profile)" \
"compose/.env does not say which slot the router runs for.
Re-run Part 2. Nothing was published."
        record "Local checks" "FAIL"; record "Delivery" "Not run"
        DELIVERY_DETAIL="the running router slot is unknown; nothing was published"
        finish_part3; return $?
    fi
    if [ "$ROUTER_NAMESPACE" != "$PARTNER_NAMESPACE" ]; then
        ROUTER_SLOT_MESSAGE=$(printf '%s\n' \
            "The router runs for slot $ROUTER_NAMESPACE, but the configured slot is $PARTNER_NAMESPACE." \
            "Re-run Part 2 to apply $PARTNER_NAMESPACE, or choose Configure inputs to restore $ROUTER_NAMESPACE. Nothing was published." \
            | fold -s -w 74)
        note_fail "3.0 (Profile)" "$ROUTER_SLOT_MESSAGE"
        record "Local checks" "FAIL"; record "Delivery" "Not run"
        DELIVERY_DETAIL="the configured slot differs from the running router; nothing was published"
        finish_part3; return $?
    fi
    if CONTEXT_RESULT=$(goat_active_context "$GOAT_PROFILE_DIR" 2>&1); then
        ACTIVE_GOAT_CONTEXT=$CONTEXT_RESULT
    else
        note_fail "3.0 (Profile)" "$CONTEXT_RESULT
Nothing was published."
        record "Local checks" "FAIL"; record "Delivery" "Not run"
        DELIVERY_DETAIL="the active goat context is invalid; nothing was published"
        finish_part3; return $?
    fi
    CLOCK_SYNCHRONIZED=1
    if ! clock_synchronized_probe; then
        CLOCK_SYNCHRONIZED=0
        warn "The host clock is not confirmed synchronized; nothing was published.
Run: sudo timedatectl set-ntp true
Then wait until this prints yes:
  timedatectl show --property=NTPSynchronized --value"
    fi

    step "3.1  Local readiness - mesh, identity, health, and containers"
    NB_STATUS=$(netbird status 2>&1)
    echo "$NB_STATUS" | fold -s -w 76 | sed 's/^/  /'
    if mesh_ready_probe "$NB_STATUS"; then
        ok "mesh management connected with at least one connected peer"
    else
        note_fail "3.1 (Mesh)" "Mesh is not ready: $MESH_NOT_READY_REASON.
Run: sudo netbird status -d"
        LOCAL_CHECKS_FAILED=1
    fi
    DOCTOR_OUT=$(GOAT_PROFILE_DIR="$GOAT_PROFILE_DIR" goat doctor --all 2>&1)
    DOCTOR_STATUS=$?
    echo "$DOCTOR_OUT" | fold -s -w 76 | sed 's/^/  /'
    if [ "$DOCTOR_STATUS" -eq 0 ] && ! echo "$DOCTOR_OUT" | grep -qiE 'fail|error'; then
        ok "goat doctor --all: cert + router checks green"
    else
        note_fail "3.1 (Health)" "goat doctor reported a problem. Check the output above, then run:
  sudo GOAT_PROFILE_DIR=$GOAT_PROFILE_DIR goat profile show"
        LOCAL_CHECKS_FAILED=1
    fi
    DOCKER_PS=$(docker ps --format '{{.Names}}\t{{.Status}}')
    echo "$DOCKER_PS" | fold -s -w 76 | sed 's/^/  /'
    ROUTER_UP=$(echo "$DOCKER_PS" | grep "^goat-moon-zenoh-router" | grep -i "Up" | grep -cv "(unhealthy)")
    if [ "$ROUTER_UP" -ge 1 ]; then
        ok "goat-moon-zenoh-router Up"
    else
        note_fail "3.1 (Router)" "The router is missing, stopped, restarting, or unhealthy.
Run: sudo docker logs goat-moon-zenoh-router"
        LOCAL_CHECKS_FAILED=1
    fi

    STATUS_JSON="$STATE_DIR/doctor/status.json"
    STATUS_FAIL_MARKER="${STATUS_JSON}.last-fail"
    T1=""
    [ ! -f "$STATUS_JSON" ] || T1=$(file_mtime "$STATUS_JSON")

    step "3.2  Delivery - baseline both counts, then publish through the running router"
    if [ "$CLOCK_SYNCHRONIZED" -eq 1 ]; then
        run_delivery_check
        case "$DELIVERY_OUTCOME" in
            Delivered) ok "$DELIVERY_OUTCOME" ;;
            "Not verified") warn "$DELIVERY_OUTCOME" ;;
            *) note_fail "3.2 (Delivery)" "$DELIVERY_OUTCOME" ;;
        esac
    else
        DELIVERY_OUTCOME="Not verified"
        DELIVERY_DETAIL="the host clock is not synchronized; run 'sudo timedatectl set-ntp true', wait for NTPSynchronized=yes, then retry Part 3"
        warn "$DELIVERY_OUTCOME"
    fi
    printf '%s\n' "$DELIVERY_DETAIL" | fold -s -w 74 | sed 's/^/  /'

    step "3.3  Local health timer"
    if [ ! -f "$STATUS_JSON" ]; then
        note_fail "3.3 (Doctor timer)" \
"$STATUS_JSON does not exist - the goat-doctor health timer never ran or was never installed.
first-boot step [6/6] installs it; re-run Part 2, or check: systemctl status goat-doctor.timer"
        LOCAL_CHECKS_FAILED=1
    else
        [ -n "$T1" ] || T1=$(file_mtime "$STATUS_JSON")
        echo "  status.json mtime: $T1 - waiting for it to advance"
        # The timer's FIRST tick after being enabled can land up to OnBootSec(30s) + one full
        # OnUnitActiveSec(60s) =~ 90s out - poll with early exit rather than a fixed sleep, so
        # a timer that's been running a while still reports back in seconds, and a timer Part 2
        # *just* installed doesn't false-negative for having not ticked yet.
        status_json_advanced_probe() {
            local t; t=$(file_mtime "$STATUS_JSON")
            [ -n "$t" ] && [ -n "$T1" ] && [ "$t" -gt "$T1" ]
        }
        TIMER_ADVANCED=0
        wait_for "status.json advancing" "$DOCTOR_TIMER_POLL_INTERVAL" "$DOCTOR_TIMER_TRIES" status_json_advanced_probe \
            && TIMER_ADVANCED=1
        T2=$(file_mtime "$STATUS_JSON")
        echo "  status.json mtime now: $T2"
        if [ -f "$STATUS_FAIL_MARKER" ]; then
            note_fail "3.3 (Doctor timer)" \
"$STATUS_FAIL_MARKER exists - the last doctor timer run failed. Re-check steps 1-2 above."
            LOCAL_CHECKS_FAILED=1
        elif [ "$TIMER_ADVANCED" -eq 1 ]; then
            ok "status.json is fresh (timestamp advanced), no .last-fail marker"
        else
            note_fail "3.3 (Doctor timer)" \
"$STATUS_JSON did not advance within $(( DOCTOR_TIMER_POLL_INTERVAL * DOCTOR_TIMER_TRIES ))s - the timer is not firing.
Check: systemctl status goat-doctor.timer   and   systemctl list-timers | grep goat-doctor"
            LOCAL_CHECKS_FAILED=1
        fi
    fi

    [ "$LOCAL_CHECKS_FAILED" -eq 0 ] && record "Local checks" "PASS" || record "Local checks" "FAIL"
    record "Delivery" "$DELIVERY_OUTCOME"
    if [ "$LOCAL_CHECKS_FAILED" -ne 0 ]; then
        PART3_RESULT="failed"
    else
        case "$DELIVERY_OUTCOME" in
            Delivered) PART3_RESULT="verified" ;;
            "Not verified") PART3_RESULT="not-verified" ;;
            *) PART3_RESULT="failed" ;;
        esac
    fi
    finish_part3
}

