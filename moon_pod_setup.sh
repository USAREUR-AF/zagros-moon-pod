mesh_json_enrollment_state() {
    python3 -c 'import json,sys
try: d=json.load(sys.stdin)
except Exception: raise SystemExit(2)
if isinstance(d.get("publicKey"),str) and d["publicKey"] and isinstance(d.get("fqdn"),str) and d["fqdn"]: raise SystemExit(0)
if str(d.get("daemonStatus","")).lower() in {"needslogin","loginfailed","sessionexpired"}: raise SystemExit(1)
raise SystemExit(2)'
}
mesh_ready_probe() {
    local status="${1:-}" peers_line connected result
    MESH_NOT_READY_REASON=""
    if [ -z "$status" ]; then
        if status=$(netbird status --json 2>/dev/null); then
            result=$(printf '%s' "$status" | python3 -c 'import json,sys
try: d=json.load(sys.stdin)
except Exception: print("unknown"); raise SystemExit
if d.get("management",{}).get("connected") is not True: print("management")
elif not isinstance(d.get("peers",{}).get("connected"),int) or d["peers"]["connected"] <= 0: print("peers")
else: print("ready")' 2>/dev/null)
            case "$result" in
                ready) return 0 ;;
                management) MESH_NOT_READY_REASON="the management connection is not Connected"; return 1 ;;
                peers) MESH_NOT_READY_REASON="no peers are connected"; return 1 ;;
            esac
        fi
        status=$(netbird status 2>&1) || {
            MESH_NOT_READY_REASON="the NetBird status could not be read"
            return 1
        }
    fi
    if ! printf '%s\n' "$status" \
        | grep -Eqi '^[[:space:]]*Management:[[:space:]]+Connected[[:space:]]*$'; then
        MESH_NOT_READY_REASON="the management connection is not Connected"
        return 1
    fi
    peers_line=$(printf '%s\n' "$status" | grep -Ei '^[[:space:]]*Peers count:' | head -1)
    connected=$(printf '%s\n' "$peers_line" \
        | sed -n 's/.*Peers count:[[:space:]]*\([0-9][0-9]*\).*/\1/p')
    if [ -z "$connected" ] || [ "$connected" -le 0 ]; then
        MESH_NOT_READY_REASON="no peers are connected"
        return 1
    fi
    return 0
}
