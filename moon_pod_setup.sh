bundle_probe() {
    [ -f "$BUNDLE_PATH" ] && return 0
    if [ -n "$BUNDLE_TARBALL" ] && [ -f "$BUNDLE_TARBALL" ]; then
        local dir; dir="$(dirname "$BUNDLE_PATH")"
        mkdir -p "$dir" && archive_members_safe "$BUNDLE_TARBALL" \
            && tar xzf "$BUNDLE_TARBALL" -C "$dir" 2>/dev/null && chmod 700 "$dir"
        [ -f "$BUNDLE_PATH" ] && return 0
    fi
    local found; mapfile -t found < <(find "$REAL_HOME" -maxdepth 5 -iname '*-goat-cli.cbor' -not -path "$REPO_DIR/*" 2>/dev/null)
    [ "${#found[@]}" -eq 1 ] && { BUNDLE_PATH="${found[0]}"; return 0; }
    return 1
}

archive_members_safe() {
    python3 - "$1" <<'PY'
import pathlib
import sys
import tarfile

try:
    with tarfile.open(sys.argv[1], "r:gz") as archive:
        for member in archive.getmembers():
            path = pathlib.PurePosixPath(member.name)
            if path.is_absolute() or ".." in path.parts:
                raise ValueError("archive member escapes the destination")
            if not (member.isfile() or member.isdir()):
                raise ValueError("archive contains a link or special file")
except (OSError, tarfile.TarError, ValueError) as error:
    print(f"unsafe or unreadable onboarding archive: {error}", file=sys.stderr)
    raise SystemExit(1)
PY
}
