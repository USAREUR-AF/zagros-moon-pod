mesh_enrollment_state() {
    local status first
    status=$(netbird status --json 2>/dev/null) || return 2
    # NetBird before 0.67 answers --json with plain text while the daemon needs a login.
    first=$(printf '%s\n' "$status" | sed -n '/[^[:space:]]/{p;q;}')
    if [[ "$first" =~ ^Daemon\ status:\ (NeedsLogin|LoginFailed|SessionExpired)[[:space:]]*$ ]]; then
        return 1
    fi
    printf '%s' "$status" | mesh_json_enrollment_state
}
