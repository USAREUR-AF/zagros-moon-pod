    part1_checklist || FAILED=1
    PART1_FAILED=$FAILED
    [ "$PART1_FAILED" -eq 0 ] && ok "PART 1 complete - host is pod-ready." || warn "PART 1 finished with failures above - Part 2's pre-flight will re-check and stop if it's not safe to continue."
    return "$PART1_FAILED"
}

